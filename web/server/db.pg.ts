/**
 * The columns that must not be compared by a linguistic collation, and the
 * tables they live in.
 *
 * `sort_key` is the spine of the product. `Store.neighbours` seeks either side
 * of one with `<` and `>`, `Shelves.booksIn` orders by it, and
 * `separators.starts_at` is compared against it to find where a shelf begins.
 * SQLite compares text byte by byte with no exceptions; Postgres compares using
 * the collation of the column, and a glibc `en_US.utf8` one ignores punctuation
 * on the first pass, folds case, and files accented characters beside their
 * unaccented forms. Two keys SQLite orders one way come back the other way.
 *
 * That does not throw and does not fail a smoke test. It reorders a shelf, or
 * moves one book past a separator, and the app then tells somebody to put a
 * book in the wrong place.
 *
 * `sort_key` also contains `\x1f`, the unit separator that joins its
 * components, and the `.` in a padded series index, both of which are exactly
 * the sort of character a linguistic collation is entitled to treat as
 * ignorable.
 *
 * Exported so a test can assert the declaration rather than trusting this
 * comment. See db.pg.test.ts, which reads the collation back out of the
 * catalogue and also shows the fixture coming out in the wrong order without it.
 */
export const SORT_KEY_COLUMNS: readonly (readonly [table: string, column: string])[] = [
  ['books', 'sort_key'],
  ['books', 'author_filing'],
  ['books', 'title_filing'],
  ['separators', 'starts_at'],
]

/** The transaction the calling code is inside, if it is inside one. */
interface TxContext {
  /**
   * The connection the transaction holds. Every statement issued from inside
   * it goes here rather than to the pool, which is the whole of the pinning.
   */
  client: PoolClient
  depth: number
}

/**
 * `Db` over node-postgres.
 *
 * Two things this has to get right, and both were settled by what `SqliteDb`
 * had to do rather than being invented here.
 *
 * **A transaction is pinned to one connection.** A pool hands out whichever
 * connection is free, so a naive implementation would send `BEGIN` down one
 * connection, an `INSERT` down a second and `COMMIT` down a third. Postgres
 * would accept every one of them: the insert would be its own autocommitted
 * transaction, the rollback would undo nothing, and on a quiet machine where
 * the pool keeps handing back the same idle connection every test would pass.
 * So the open transaction is carried in an `AsyncLocalStorage` and `all`, `get`
 * and `run` look there before they look at the pool.
 *
 * It has to be the async context rather than a field on the class for the same
 * reason `SqliteDb` needed one: `Shelves.moveAcrossBoundary` opens a
 * transaction and then calls `remove`, which opens one of its own **through the
 * handle the class holds** rather than the one `tx` passed its work. A field
 * would also catch an unrelated request's statement and pull it into a
 * transaction that may then roll back.
 *
 * **What it does not need is `SqliteDb`'s lock.** That exists because
 * better-sqlite3 has one connection, so keeping a transaction's statements
 * contiguous meant making everything else queue behind it. Postgres has real
 * connections: an unrelated statement runs on another one, concurrently, which
 * is the point of moving to it.
 */
export class PgDb implements Db {
  private readonly context = new AsyncLocalStorage<TxContext>()

  constructor(private readonly pool: pg.Pool) {}

  async all<Row>(sql: string, params?: Params): Promise<Row[]> {
    const result = await this.query(sql, params)
    return result.rows as Row[]
  }

  async get<Row>(sql: string, params?: Params): Promise<Row | undefined> {
    const result = await this.query(sql, params)
    return result.rows[0] as Row | undefined
  }

  async run(sql: string, params?: Params): Promise<{ changes: number }> {
    const result = await this.query(sql, params)
    // `changes` is what the stores read and what better-sqlite3 called it.
    // `CaptureQueue.claim` decides whether a claim was taken from this number,
    // so a null read as 0 would report every successful claim as contended.
    return { changes: result.rowCount ?? 0 }
  }

  async tx<T>(work: (db: Db) => Promise<T>): Promise<T> {
    const open = this.context.getStore()
    if (open) return this.savepoint(open, work)

    const client = await this.pool.connect()
    try {
      await client.query('BEGIN')
      try {
        const result = await this.context.run({ client, depth: 1 }, () => work(this))
        await client.query('COMMIT')
        return result
      } catch (error) {
        await client.query('ROLLBACK')
        throw error
      }
    } finally {
      // Back to the pool whatever happened. A connection leaked here is one
      // fewer for the rest of the process, and the pool's default size is ten.
      client.release()
    }
  }

  async close(): Promise<void> {
    await this.pool.end()
  }

  /**
   * The one place a statement is sent. Inside a transaction it goes to that
   * transaction's connection; outside one it goes to the pool, which is free to
   * run it alongside anything else.
   */
  private async query(sql: string, params?: Params): Promise<pg.QueryResult> {
    // `numbered` rather than `anonymous`, and that is the whole of the dialect
    // difference in this method. Every statement in the three stores has been
    // going through this translator on SQLite since stage E, so the translation
    // itself is exercised by the entire existing suite.
    const { text, values } = bindParams(sql, params, numbered)
    const open = this.context.getStore()
    if (open) return open.client.query({ text, values })
    return this.pool.query({ text, values })
  }

  /**
   * A transaction inside a transaction, on the connection the outer one holds.
   * Postgres refuses a nested `BEGIN` with a warning and then quietly carries
   * on in the outer transaction, so the inner one's rollback would undo the
   * outer one's work. `SAVEPOINT` is the spelling that means what the caller
   * asked for, and it is the same word SQLite uses.
   */
  private async savepoint<T>(open: TxContext, work: (db: Db) => Promise<T>): Promise<T> {
    const name = `bookscan_${open.depth}`
    await open.client.query(`SAVEPOINT ${name}`)
    try {
      const result = await this.context.run(
        { client: open.client, depth: open.depth + 1 },
        () => work(this),
      )
      await open.client.query(`RELEASE SAVEPOINT ${name}`)
      return result
    } catch (error) {
      await open.client.query(`ROLLBACK TO SAVEPOINT ${name}`)
      await open.client.query(`RELEASE SAVEPOINT ${name}`)
      throw error
    }
  }
}

/**
 * Create the schema and seed it, then hand back a `Db`.
 *
 * The seeding is the same two statements db.ts runs, spelled the same way.
 * Stage D made them dialect-neutral against SQLite, which is where that was
 * cheap to prove; this is where it gets used.
 */
export async function applySchema(pool: pg.Pool): Promise<void> {
  // Straight at the pool, not through `Db.run`, and for two reasons. `Db` has
  // no `exec` because schema creation is the only caller that wants
  // multi-statement SQL and that is per-dialect. And node-postgres picks its
  // wire protocol from whether values were supplied: the translator always
  // hands back an array, which selects the extended protocol, and that one
  // refuses more than one command per statement.
  await pool.query(SCHEMA)

  const db = new PgDb(pool)
  const seed = `INSERT INTO shelf_ranges
       (shelf_range, start_label, start_shelf, start_area, note)
     VALUES (?, ?, ?, ?, ?)
     ON CONFLICT DO NOTHING`
  await db.run(seed, ['fiction', '1A', 1, 0, 'Starts on the first bookcase'])
  await db.run(seed, ['nonfiction', '4A', 4, 0, 'Bookcase 4 is dedicated to non-fiction'])

  // The two repairs db.ts makes to a seed written before ranges had a starting
  // bookcase. Kept for the same reason the seed is: a scratch Postgres created
  // by an older revision of this file is a database somebody may still have.
  await db.run(
    "UPDATE shelf_ranges SET start_shelf = 4, start_area = 0, start_label = '4A' " +
    "WHERE shelf_range = 'nonfiction' AND start_label = 'S4'",
  )
  await db.run(
    "UPDATE shelf_ranges SET start_label = '1A' WHERE shelf_range = 'fiction' " +
    "AND start_label != '1A'",
  )
}

/**
 * Open the catalogue on Postgres.
 *
 * Asynchronous where `openDatabase` is synchronous, which is the one thing this
 * costs the startup path: `index.ts` now awaits its database rather than having
 * it by the time the module finishes evaluating.
 */
export async function openPostgres(connectionString: string): Promise<Db> {
  const pool = new Pool({ connectionString })
  try {
    await applySchema(pool)
  } catch (error) {
    await pool.end()
    throw error
  }
  return new PgDb(pool)
}
